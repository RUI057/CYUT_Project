    ap.add_argument("--show-fail", action="store_true")
    args = ap.parse_args()

    os.environ["POLISH_BACKEND"] = "local"
    from src import translate, local_llm
    os.environ.pop("GEMINI_API_KEY", None)           # 評測只看本機模型，不連雲端
    translate._order = lambda: ["local"]
    if args.beams is not None:
        translate.BEAMS = max(1, args.beams)
