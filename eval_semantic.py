def norm(s):
    s = re.sub(r"[\s，,、]", "", s or "")
    s = s.replace("！", "。").replace("!", "。").replace("?", "？")
    s = re.sub(r"好(?=[%s])" % _ADJ, "", s)        # 好累 = 累
    return re.sub(r"[很太真了的在]", "", s)         # 虛詞差異不算錯


def judge(case, out):
    return norm(out) in {norm(g) for g in case["gold"]}


